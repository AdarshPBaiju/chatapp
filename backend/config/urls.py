import os

from django.contrib import admin
from django.urls import include, path
from drf_spectacular.views import (
    SpectacularAPIView,
    SpectacularRedocView,
    SpectacularSwaggerView,
)
from django.conf import settings
from django.conf.urls.static import static

urlpatterns = [
    # Auth & Identity
    path("api/v1/auth/", include("authentication.api.v1.urls")),
    # Users & Profiles
    path("", include("users.urls")),
    # Chat & Messaging
    path("api/chat/", include("chat.urls")),
    # API Documentation
    path("api/schema/", SpectacularAPIView.as_view(), name="schema"),
    path(
        "api/docs/",
        SpectacularSwaggerView.as_view(url_name="schema"),
        name="swagger-ui",
    ),
    path(
        "api/redoc/",
        SpectacularRedocView.as_view(url_name="schema"),
        name="redoc",
    ),
]

# Admin URL control via environment variable
admin_url = os.environ.get("ADMIN_URL", "").strip()
if admin_url:
    urlpatterns.append(path(f"{admin_url}/", admin.site.urls))

# Serve static/media files during development
if settings.DEBUG:
    urlpatterns += static(settings.STATIC_URL, document_root=settings.STATIC_ROOT)
    urlpatterns += static(settings.MEDIA_URL, document_root=settings.MEDIA_ROOT)
